import Phaser from 'phaser';
import './style.css';
import { createGameConfig } from './config/game';
import { BootScene } from './scenes/BootScene';
import { DriveScene } from './scenes/DriveScene';
import { EngineAudio } from './systems/AudioManager';
import { Controls } from './systems/Input';
import { EventBus } from './systems/EventBus';
import { HUD } from './ui/HUD';
import { validateCatalog } from './physics/catalog';
import { Simulation } from './physics/simulation';

validateCatalog();
const sim = new Simulation();
const controls = new Controls();
const audio = new EngineAudio();
const events = new EventBus();
let hud: HUD | undefined;
const scene = new DriveScene(sim, () => controls.read(), fps => hud?.update(fps), batch => events.publish(batch));
new Phaser.Game(createGameConfig([new BootScene(), scene]));
hud = new HUD(sim, scene, controls, audio);
events.subscribe(batch => hud?.onEvents(batch));
